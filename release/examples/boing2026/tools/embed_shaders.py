#!/usr/bin/env python3
"""Writes boing2026_shaders.h from shaders/*: each file becomes a C string
constant byte for byte, so ogles2 finds the same program hash as the offline
compiler gave the shipped .v3dp files. usage: embed_shaders.py OUT FILE..."""
import os
import sys

out = sys.argv[1]
lines = ["/* Generated by tools/embed_shaders.py from shaders/: edit those. */\n"]
for path in sys.argv[2:]:
    name = os.path.basename(path).replace(".", "_")
    text = open(path, "rb").read().decode("ascii")
    lines.append("static const char %s[] =\n" % name)
    for line in text.splitlines(True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        lines.append('    "%s"\n' % esc)
    lines.append("    ;\n\n")
open(out, "w", newline="\n").write("".join(lines))
