static const char height_fs[] =
    "precision highp float;\n"
    "uniform float u_time;\n"
    "uniform float u_texel;\n"
    "uniform float u_extent;\n"
    "\n"
    "#define DRAG_MULT 0.38\n"
    "\n"
    "// The coarse water surface (8 octaves), once per frame for a square of the\n"
    "// sea: its height (red, 0..1; the height is value * WATER_DEPTH -\n"
    "// WATER_DEPTH) and its slope in x and z (green, blue: slope / 4 + 0.5),\n"
    "// summed with it through the drag by the chain rule (J: how the drifted\n"
    "// sample position moves with the start position). The ray march reads the\n"
    "// height; the shading takes the slope as the coarse normal.\n"
    "void main() {\n"
    "    vec2 position = gl_FragCoord.xy * u_texel - u_extent;\n"
    "    float len = length(position);\n"
    "    float phase = len * 0.1;\n"
    "    vec2 dphase = position * (0.1 / max(len, 0.0001));\n"
    "    vec2 p = vec2(0.0, 1.0); /* (sin, cos) of the octave's angle, 0 at first */\n"
    "    float frequency = 1.0, timeMul = 2.0, weight = 1.0;\n"
    "    float sum = 0.0, weights = 0.0;\n"
    "    vec2 grad = vec2(0.0);\n"
    "    mat2 J = mat2(1.0);\n"
    "    for (int i = 0; i < 8; i++) {\n"
    "        float x = dot(p, position) * frequency + u_time * timeMul + phase;\n"
    "        float sx = sin(x), cx = cos(x);\n"
    "        float wave = exp(sx - 1.0);\n"
    "        vec2 dx = (p * J) * frequency + dphase;\n"
    "        grad += dx * (wave * cx * weight);\n"
    "        float k = wave * (sx - cx * cx) * weight * DRAG_MULT;\n"
    "        position -= p * (wave * cx * weight * DRAG_MULT);\n"
    "        J += mat2(p * (dx.x * k), p * (dx.y * k));\n"
    "        sum += wave * weight;\n"
    "        weights += weight;\n"
    "        weight *= 0.8;\n"
    "        frequency *= 1.18;\n"
    "        timeMul *= 1.07;\n"
    "        /* The next octave's angle is 1232.399963 rad on: rotate (sin, cos). */\n"
    "        p = vec2(p.x * 0.625017174 + p.y * 0.780610999, p.y * 0.625017174 - p.x * 0.780610999);\n"
    "    }\n"
    "    gl_FragColor = vec4(sum / weights, clamp(grad / weights * 0.25 + 0.5, 0.0, 1.0), 1.0);\n"
    "}\n";

static const char sky_fs[] =
    "precision highp float;\n"
    "uniform vec3 u_sun;\n"
    "varying vec2 v_tc;\n"
    "\n"
    "// The sky's colour depends only on how high the ray points (y) and how\n"
    "// close it points to the sun (d = cos of the angle): a small table of it,\n"
    "// once per frame, x = d from -1 to 1, y = height from 0 to 1. Stored as\n"
    "// RGBM (colour / (8 * alpha)): the sky is brighter than 1.\n"
    "void main() {\n"
    "    float d = v_tc.x * 2.0 - 1.0;\n"
    "    float y = v_tc.y;\n"
    "    float st = 1.0 / (y + 0.1);\n"
    "    float st2 = 1.0 / (u_sun.y * 11.0 + 1.0);\n"
    "    float raysundt = d * d;\n"
    "    float sundt = pow(max(0.0, d), 8.0);\n"
    "    float mymie = sundt * st * 0.2;\n"
    "    vec3 suncolor = mix(vec3(1.0), max(vec3(0.0), vec3(1.0) - vec3(5.5, 13.0, 22.4) / 22.4), st2);\n"
    "    vec3 bluesky = vec3(5.5, 13.0, 22.4) / 22.4 * suncolor;\n"
    "    vec3 bluesky2 = max(vec3(0.0), bluesky - vec3(5.5, 13.0, 22.4) * 0.002 * (st - 6.0 * u_sun.y * u_sun.y));\n"
    "    bluesky2 *= st * (0.24 + raysundt * 0.24);\n"
    "    vec3 c = (bluesky2 * (1.0 + pow(1.0 - y, 3.0)) + mymie * suncolor) * 0.5;\n"
    "    float m = clamp(max(max(c.r, c.g), max(c.b, 0.000001)) / 8.0, 1.0 / 255.0, 1.0);\n"
    "    m = ceil(m * 255.0) / 255.0;\n"
    "    gl_FragColor = vec4(c / (m * 8.0), m);\n"
    "}\n";
