static const char boingocean_fs[] =
    "precision highp float;\n"
    "uniform float u_time;\n"
    "uniform vec3 u_sun;\n"
    "uniform vec3 u_eye;\n"
    "uniform vec3 u_ball;\n"
    "uniform vec3 u_px;\n"
    "uniform vec3 u_py;\n"
    "uniform vec3 u_pz;\n"
    "uniform vec3 u_ambient;\n"
    "uniform sampler2D u_height; /* the coarse water height, made this frame */\n"
    "uniform sampler2D u_sky;    /* the sky table, made this frame (RGBM) */\n"
    "varying vec3 v_ray;\n"
    "\n"
    "#define DRAG_MULT 0.38\n"
    "#define WATER_DEPTH 1.0\n"
    "#define BALL_R 0.8\n"
    "#define WAVE_SLOPE 0.5 /* the coarse waves' steepest slope, about */\n"
    "#define EXTENT 30.0 /* the height texture covers -EXTENT..EXTENT in x and z */\n"
    "\n"
    "// The coarse water height at xz, from the texture.\n"
    "float seaHeight(vec2 xz) {\n"
    "    return texture2D(u_height, xz * (0.5 / EXTENT) + 0.5).r * WATER_DEPTH - WATER_DEPTH;\n"
    "}\n"
    "\n"
    "// The distance along the view ray to the water, marching from the wave\n"
    "// crests' plane (at distance t). Past the texture's square the sea is far\n"
    "// enough to take the first point as the hit.\n"
    "float raymarchwater(vec3 ray, float t) {\n"
    "    // The longest step that cannot pass through a wave: the ray sinks by\n"
    "    // -ray.y a unit, the surface rises by at most its steepest slope\n"
    "    // (WAVE_SLOPE) a unit, and the gap between them must not close. A ray\n"
    "    // near the horizon so takes long steps, where the gap along the ray\n"
    "    // took many short ones. The hit tolerance grows with the distance.\n"
    "    float k = 1.0 / (WAVE_SLOPE - ray.y);\n"
    "    for (int i = 0; i < 8; i++) {\n"
    "        vec3 pos = u_eye + ray * t;\n"
    "        if (abs(pos.x) > EXTENT || abs(pos.z) > EXTENT)\n"
    "            return t;\n"
    "        float gap = pos.y - seaHeight(pos.xz);\n"
    "        if (gap < 0.01 + t * 0.002)\n"
    "            return t;\n"
    "        t += gap * k;\n"
    "    }\n"
    "    return t;\n"
    "}\n"
    "\n"
    "// The surface normal: the coarse waves' slope from the height texture (the\n"
    "// march's last read returns it), plus three short sine ripples for detail,\n"
    "// fading out with distance where they would be smaller than a pixel.\n"
    "vec3 seaNormal(vec2 xz, vec2 coarse, float dist) {\n"
    "    vec2 grad = coarse;\n"
    "    float fade = clamp(1.0 - dist * 0.06, 0.0, 1.0);\n"
    "    if (fade > 0.0) {\n"
    "        vec2 p = vec2(0.6, 0.8);\n"
    "        float frequency = 3.8, amp = 0.03 * fade;\n"
    "        for (int i = 0; i < 3; i++) {\n"
    "            float x = dot(p, xz) * frequency + u_time * (frequency * 0.9 + 2.0);\n"
    "            grad += p * (cos(x) * frequency * amp);\n"
    "            frequency *= 1.5;\n"
    "            amp *= 0.7;\n"
    "            p = vec2(p.x * 0.625017174 + p.y * 0.780610999, p.y * 0.625017174 - p.x * 0.780610999);\n"
    "        }\n"
    "    }\n"
    "    return normalize(vec3(-grad.x, 1.0, -grad.y));\n"
    "}\n"
    "\n"
    "// The sky towards dir, from the table (dir.y >= 0).\n"
    "vec3 sky(vec3 dir) {\n"
    "    vec4 c = texture2D(u_sky, vec2(dot(dir, u_sun) * 0.5 + 0.5, dir.y));\n"
    "    return c.rgb * (c.a * 8.0);\n"
    "}\n"
    "\n"
    "// The sun's disc and glare: 210 * pow(d, 720) is below 0.005 outside about\n"
    "// 10 degrees of the sun (d < 0.985), so it is worked out only inside.\n"
    "float sun(vec3 dir) {\n"
    "    float d = dot(dir, u_sun);\n"
    "    return d > 0.985 ? pow(d, 720.0) * 210.0 : 0.0;\n"
    "}\n"
    "\n"
    "// Tone mapping: Narkowicz's fit of the ACES curve, then gamma 2 (sqrt):\n"
    "// a few multiply-adds instead of two matrices and three powers.\n"
    "vec3 aces(vec3 c) {\n"
    "    c = clamp(c * (2.51 * c + 0.03) / (c * (2.43 * c + 0.59) + 0.14), 0.0, 1.0);\n"
    "    return sqrt(c);\n"
    "}\n"
    "\n"
    "float hitBall(vec3 ro, vec3 rd) {\n"
    "    vec3 oc = ro - u_ball;\n"
    "    float b = dot(oc, rd);\n"
    "    float disc = b * b - (dot(oc, oc) - BALL_R * BALL_R);\n"
    "    if (disc < 0.0)\n"
    "        return -1.0;\n"
    "    float t = -b - sqrt(disc);\n"
    "    return t > 0.0 ? t : -1.0;\n"
    "}\n"
    "\n"
    "vec3 shadeBall(vec3 p, vec3 rd) {\n"
    "    vec3 n = (p - u_ball) * (1.0 / BALL_R);\n"
    "    vec3 q = vec3(dot(n, u_px), dot(n, u_py), dot(n, u_pz));\n"
    "    float lon = atan(q.z, q.x) * (16.0 / 6.2831853);\n"
    "    float lat = asin(clamp(q.y, -1.0, 1.0)) * (8.0 / 3.1415927);\n"
    "    vec3 albedo = mod(floor(lon) + floor(lat), 2.0) > 0.5 ? vec3(0.80, 0.03, 0.02) : vec3(0.85);\n"
    "    float diff = max(dot(n, u_sun), 0.0);\n"
    "    vec3 col = albedo * (diff * vec3(0.9, 0.855, 0.765) + u_ambient + vec3(0.02, 0.05, 0.06) * max(-n.y, 0.0));\n"
    "    vec3 h = normalize(u_sun - rd);\n"
    "    col += pow(max(dot(n, h), 0.0), 120.0) * 1.5;\n"
    "    vec3 rr = reflect(rd, n);\n"
    "    vec3 env;\n"
    "    if (rr.y >= 0.0)\n"
    "        env = sky(rr) + sun(rr);\n"
    "    else\n"
    "        env = mix(vec3(0.004, 0.012, 0.025), sky(normalize(vec3(rr.x, 0.02, rr.z))) * 0.6, exp(rr.y * 8.0));\n"
    "    float f1 = 1.0 - max(dot(n, -rd), 0.0), f2 = f1 * f1;\n"
    "    float fres = 0.08 + 0.92 * f2 * f2 * f1;\n"
    "    return mix(col, env, fres);\n"
    "}\n"
    "\n"
    "vec3 shadeWater(vec3 origin, vec3 ray, float dist) {\n"
    "    vec3 hitPos = origin + ray * dist;\n"
    "    vec2 coarse = (texture2D(u_height, hitPos.xz * (0.5 / EXTENT) + 0.5).gb - 0.5) * (4.0 * WATER_DEPTH);\n"
    "    vec3 N = seaNormal(hitPos.xz, coarse, dist);\n"
    "    N = mix(N, vec3(0.0, 1.0, 0.0), 0.8 * min(1.0, sqrt(dist * 0.01) * 1.1));\n"
    "    float f1 = 1.0 - max(0.0, dot(-N, ray)), f2 = f1 * f1;\n"
    "    float fresnel = 0.04 + 0.96 * f2 * f2 * f1;\n"
    "    vec3 R = normalize(reflect(ray, N));\n"
    "    R.y = abs(R.y);\n"
    "    vec3 reflection = sky(R) + sun(R);\n"
    "    vec3 body = vec3(0.0293, 0.0698, 0.1717) * 0.1 * (0.2 + (hitPos.y + WATER_DEPTH) / WATER_DEPTH);\n"
    "    // The ball can show in the water (reflected, through it, its waterline)\n"
    "    // only near it: elsewhere none of that is worked out.\n"
    "    float r = length(hitPos.xz - u_ball.xz);\n"
    "    float ring = 0.0;\n"
    "    if (r < BALL_R * 4.0) {\n"
    "        float tr = hitBall(hitPos, R);\n"
    "        if (tr > 0.0)\n"
    "            reflection = shadeBall(hitPos + R * tr, R);\n"
    "        vec3 rf = refract(ray, N, 0.75);\n"
    "        float tu = hitBall(hitPos, rf);\n"
    "        if (tu > 0.0) {\n"
    "            vec3 under = shadeBall(hitPos + rf * tu, rf) * vec3(0.3, 0.5, 0.58);\n"
    "            body = mix(body, under, exp(-tu * 1.2) * 0.85);\n"
    "            fresnel *= 0.6;\n"
    "        }\n"
    "        float dy = hitPos.y - u_ball.y;\n"
    "        float edge = r - sqrt(max(BALL_R * BALL_R - dy * dy, 0.0));\n"
    "        ring = smoothstep(0.03, 0.0, edge) * step(0.0, edge) * step(abs(dy), BALL_R);\n"
    "    }\n"
    "    vec3 C = fresnel * reflection + (1.0 - fresnel) * body;\n"
    "    C = mix(C, C * 1.6 + vec3(0.01, 0.015, 0.02), ring * 0.5);\n"
    "    // Haze: the water fades into the horizon's colour before the height\n"
    "    // texture's edge, where it would stop.\n"
    "    vec2 far = abs(hitPos.xz) * (1.0 / EXTENT);\n"
    "    float haze = smoothstep(0.55, 0.95, max(far.x, far.y));\n"
    "    if (haze > 0.0)\n"
    "        C = mix(C, sky(normalize(vec3(ray.x, 0.03, ray.z))), haze);\n"
    "    return C;\n"
    "}\n"
    "\n"
    "void main() {\n"
    "    vec3 ray = normalize(v_ray);\n"
    "    float tb = hitBall(u_eye, ray);\n"
    "    vec3 C;\n"
    "    if (ray.y >= 0.0) {\n"
    "        C = tb > 0.0 ? shadeBall(u_eye + ray * tb, ray) : sky(ray) + sun(ray);\n"
    "    } else {\n"
    "        float dist = raymarchwater(ray, -u_eye.y / ray.y);\n"
    "        if (tb > 0.0) {\n"
    "            vec3 bp = u_eye + ray * tb;\n"
    "            if (bp.y < seaHeight(bp.xz)) {\n"
    "                dist = min(dist, tb - 0.02);\n"
    "                tb = -1.0;\n"
    "            }\n"
    "        }\n"
    "        if (tb > 0.0 && tb < dist)\n"
    "            C = shadeBall(u_eye + ray * tb, ray);\n"
    "        else\n"
    "            C = shadeWater(u_eye, ray, dist);\n"
    "    }\n"
    "    gl_FragColor = vec4(aces(C * 2.0), 1.0);\n"
    "}\n";

