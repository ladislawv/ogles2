#!/bin/bash
# Compiles the program ogles2 clears several render targets with
# (EXT_draw_buffers: a glClear confined by the scissor box or write masks,
# or after draws, writes the clear colour to every draw buffer; draw.c) and
# writes it into ogles2/clear_mrt_v3dp.h as a .v3dp image the library loads
# from memory. Run in WSL after the host v3dglslc changes (its .v3dp records
# the Mesa commit the loader checks):  bash tools/clear_mrt/make_header.sh
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
V3DGLSLC=${V3DGLSLC:-$HOME/ogles2-build/v3dglslc/host/v3dglslc}
W=$(mktemp -d)
cp "$HERE/clear_mrt.vert" "$HERE/clear_mrt.frag" "$W/"
(cd "$W" && "$V3DGLSLC" -o . clear_mrt.vert clear_mrt.frag > log.txt 2>&1) || { cat "$W/log.txt"; exit 1; }
python3 - "$W/clear_mrt-clear_mrt.v3dp" "$REPO/ogles2/clear_mrt_v3dp.h" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
out = ["/* Generated by tools/clear_mrt/make_header.sh from clear_mrt.vert and",
       " * clear_mrt.frag: do not edit. The program draw.c clears several render",
       " * targets with (EXT_draw_buffers), as a .v3dp image (v3dp/FORMAT.md). */",
       "static const UBYTE clear_mrt_v3dp[%d] = {" % len(data)]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
out.append("};")
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
print("%s: %d bytes" % (sys.argv[2], len(data)))
PY
rm -rf "$W"
