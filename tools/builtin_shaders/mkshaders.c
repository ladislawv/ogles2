/*
 * Assembles the built-in program's three shaders with PiStorm3D's QPU
 * assembler (v3dcore/hw/v3d_assembler.c) and prints them as a C header of
 * little-endian machine code, ready to copy into GPU memory.
 *
 * An Amiga program, run under vamos at build time (make builtin-shaders):
 * the assembler is m68k code with Amiga types, and running it unchanged
 * means the bytes are exactly those PiStorm3D assembles on the A1200. The
 * output, ogles2/builtin_shaders.h, is checked in; the library does not
 * carry the assembler or its 95 shader sources.
 *
 * The program is PiStorm3D's smooth-shaded, untextured pairing (plan
 * section 9, M1): COORDINATE_TEXTURED (binning; position only),
 * VERTEX_SMOOTH and FRAGMENT_UNTEXTURED_SMOOTH.
 */
#include <stdio.h>
#include <string.h>
#include "v3d_device.h"
#include "v3d_shader_assembler.h"

static void emit(const char *name, int variant)
{
    const V3DAssembledShader *s = &v3d_shader_variants[variant];
    int i, b;
    printf("\n/* %s: %d instructions */\n", name, s->numInstructions);
    printf("static const unsigned char builtin_%s[%d] = {\n", name, s->numInstructions * 8);
    for (i = 0; i < s->numInstructions; i++) {
        unsigned long long w = (unsigned long long)s->instructions[i];
        printf("   ");
        for (b = 0; b < 8; b++) /* little-endian: what the QPU fetches */
            printf(" 0x%02x,", (unsigned)((w >> (8 * b)) & 0xff));
        printf(" /* %08lx%08lx */\n", (unsigned long)(w >> 32), (unsigned long)w);
    }
    printf("};\n");
}

int main(void)
{
    V3DDevice dev;
    memset(&dev, 0, sizeof(dev));
    dev.deviceInfo.ver = 42; /* the Pi 4's V3D 4.2 */
    dev.deviceInfo.has_accumulators = 1;
    if (!v3d_assemble_builtin_shaders(&dev)) {
        fprintf(stderr, "mkshaders: the assembler failed\n");
        return 20;
    }
    printf("/* Generated by tools/builtin_shaders/mkshaders.c (make builtin-shaders). Do not edit.\n"
           " * PiStorm3D 29.1's assembler and shader sources (v3dcore/hw/v3d_assembler.c). */\n");
    emit("coordinate", V3D_SHADER_VARIANT_COORDINATE_TEXTURED);
    emit("vertex_smooth", V3D_SHADER_VARIANT_VERTEX_SMOOTH);
    emit("fragment_smooth", V3D_SHADER_VARIANT_FRAGMENT_UNTEXTURED_SMOOTH);
    return 0;
}
