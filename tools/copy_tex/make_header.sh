#!/bin/bash
# Compiles the program ogles2 copies the framebuffer into a texture with
# (glCopyTexImage2D and glCopyTexSubImage2D on the GPU: a quad drawn from
# the picture into the texture level; copy.c, draw.c) and writes it into
# ogles2/copy_tex_v3dp.h as a .v3dp image the library loads from memory.
# Run in WSL after the host v3dglslc changes (its .v3dp records the Mesa
# commit the loader checks):  bash tools/copy_tex/make_header.sh
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
V3DGLSLC=${V3DGLSLC:-$HOME/ogles2-build/v3dglslc/host/v3dglslc}
W=$(mktemp -d)
cp "$HERE/copy_tex.vert" "$HERE/copy_tex.frag" "$W/"
(cd "$W" && "$V3DGLSLC" -o . copy_tex.vert copy_tex.frag > log.txt 2>&1) || { cat "$W/log.txt"; exit 1; }
python3 - "$W/copy_tex-copy_tex.v3dp" "$REPO/ogles2/copy_tex_v3dp.h" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
out = ["/* Generated by tools/copy_tex/make_header.sh from copy_tex.vert and",
       " * copy_tex.frag: do not edit. The program draw.c copies the framebuffer",
       " * into a texture with (copy.c), as a .v3dp image (v3dp/FORMAT.md). */",
       "static const UBYTE copy_tex_v3dp[%d] = {" % len(data)]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
out.append("};")
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
print("%s: %d bytes" % (sys.argv[2], len(data)))
PY
rm -rf "$W"
