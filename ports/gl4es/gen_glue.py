#!/usr/bin/env python3
"""Writes ogles2_glue.c, gl4es's GLES2 back end on AmigaOS 3 (ports/gl4es).

gl4es reaches GLES2 through os4GetProcAddress(name) (src/agl/amigaos.c on
AmigaOS 4, where every entry calls IOGLES2->glName). Here each entry of
ogles2.library's dispatch table (libraries/ogles2_dispatch.h, generated by
gen/gen_ogles2.py) becomes a static function that calls the table with the
program's current context, and os4GetProcAddress maps the GL names to them.
The functions are not named gl*: gl4es exports those names itself.

With the environment variable GL4ES_GLUE_PROFILE set, every call is counted
and timed (the Pi's 1 MHz system timer), and gl4es_glue_profile() prints the
functions that took longest: how a program's time splits between itself and
gl4es on one side and ogles2.library on the other (M6, Quake III).

    gen_glue.py OGLES2_DISPATCH_H OUT_C [PROFILE_ENV]

PROFILE_ENV names the environment variable instead (ports/ioq3-gl2 uses the
same glue with its own).
"""
import re
import sys


def main():
    header, out = sys.argv[1], sys.argv[2]
    env = sys.argv[3] if len(sys.argv) > 3 else "GL4ES_GLUE_PROFILE"
    text = open(header, encoding="utf-8").read()
    member = re.compile(r"^\s*(?P<ret>[^;(]+?)\s*\(\*GL(?P<name>\w+)\)\((?P<params>[^)]*)\);", re.M)
    funcs = []
    for m in member.finditer(text):
        params = [p.strip() for p in m.group("params").split(",")]
        assert params[0].startswith("struct OGLES2Context"), m.group(0)
        params = params[1:]
        args = []
        for p in params:
            a = re.search(r"(\w+)\s*(\[\s*\d*\s*\])?$", p)
            assert a, p
            args.append(a.group(1))
        funcs.append((m.group("ret").strip(), m.group("name"), params, args))
    lines = [
        "/* GENERATED by ports/gl4es/gen_glue.py from libraries/ogles2_dispatch.h - do not edit. */",
        "/* gl4es's GLES2 back end on AmigaOS 3: ogles2.library's dispatch table. */",
        "#include <stdio.h>",
        "#include <stdlib.h>",
        "#include <string.h>",
        "#include <exec/types.h>",
        "#include <libraries/ogles2_dispatch.h>",
        "",
        "extern const struct OGLES2Dispatch *OGLES2Dispatch; /* libogles2.a */",
        "extern struct OGLES2Context *OGLES2CurrentContext;",
        "BOOL OGLES2Open(void);",
        "void OGLES2Close(void);",
        "",
        "/* %s: calls and microseconds per function. */" % env,
        "#define GLUE_N %d" % len(funcs),
        "static int glue_prof;",
        "static ULONG glue_calls[GLUE_N], glue_us[GLUE_N];",
        "static const char *const glue_names[GLUE_N] = {",
    ]
    for ret, name, params, args in funcs:
        lines.append('    "gl%s",' % name)
    lines += [
        "};",
        "",
        "static ULONG glue_now(void)",
        "{",
        "    ULONG v = *(volatile ULONG *)(0xF2000000 + 0x3004); /* the system timer, little-endian */",
        "    return (v >> 24) | ((v >> 8) & 0xFF00) | ((v << 8) & 0xFF0000) | (v << 24);",
        "}",
        "",
        "static void glue_add(int i, ULONG t0)",
        "{",
        "    glue_calls[i]++;",
        "    glue_us[i] += glue_now() - t0;",
        "}",
        "",
        "/* The functions that took longest, then the counts reset. */",
        "void gl4es_glue_profile(ULONG frames)",
        "{",
        "    ULONG total = 0, calls = 0;",
        "    int i, k, best;",
        "    if (!glue_prof)",
        "        return;",
        "    for (i = 0; i < GLUE_N; i++) {",
        "        total += glue_us[i];",
        "        calls += glue_calls[i];",
        "    }",
        "    if (!frames)",
        "        frames = 1;",
        "    printf(\"glue profile: %lu frames, per frame %lu calls into ogles2.library taking %lu us\\n\",",
        "           (unsigned long)frames, (unsigned long)(calls / frames), (unsigned long)(total / frames));",
        "    for (k = 0; k < 25; k++) {",
        "        best = -1;",
        "        for (i = 0; i < GLUE_N; i++)",
        "            if (glue_us[i] && (best < 0 || glue_us[i] > glue_us[best]))",
        "                best = i;",
        "        if (best < 0)",
        "            break;",
        "        printf(\"glue profile: %-32s %7lu calls %8lu us a frame\\n\", glue_names[best],",
        "               (unsigned long)(glue_calls[best] / frames), (unsigned long)(glue_us[best] / frames));",
        "        glue_us[best] = 0;",
        "    }",
        "    memset(glue_calls, 0, sizeof(glue_calls));",
        "    memset(glue_us, 0, sizeof(glue_us));",
        "}",
        "",
    ]
    for i, (ret, name, params, args) in enumerate(funcs):
        call = "OGLES2Dispatch->GL%s(%s)" % (name, ", ".join(["OGLES2CurrentContext"] + args))
        lines.append("static %s Amigl%s(%s)" % (ret, name, ", ".join(params) or "void"))
        lines.append("{")
        lines.append("    if (glue_prof) {")
        lines.append("        ULONG t0 = glue_now();")
        if ret == "void":
            lines.append("        %s;" % call)
            lines.append("        glue_add(%d, t0);" % i)
            lines.append("        return;")
        else:
            lines.append("        %s r = %s;" % (ret, call))
            lines.append("        glue_add(%d, t0);" % i)
            lines.append("        return r;")
        lines.append("    }")
        lines.append("    %s%s;" % ("" if ret == "void" else "return ", call))
        lines.append("}")
        lines.append("")
    lines += [
        "/* gl4es (gl/loader.c): open the library; *lib only has to be non-NULL. */",
        "void os4OpenLib(void **lib)",
        "{",
        "    *lib = OGLES2Open() ? (void *)OGLES2Dispatch : NULL;",
        "    glue_prof = getenv(\"%s\") != NULL;" % env,
        "}",
        "",
        "void os4CloseLib(void)",
        "{",
        "    OGLES2Close();",
        "}",
        "",
        "/* gl4es (gl/loader.c): a GLES2 function by its name, NULL if there is none. */",
        "void *os4GetProcAddress(const char *name)",
        "{",
        "    if (!OGLES2Dispatch || !name || name[0] != 'g' || name[1] != 'l')",
        "        return NULL;",
    ]
    for ret, name, params, args in funcs:
        lines.append('    if (!strcmp(name + 2, "%s"))' % name)
        lines.append("        return (void *)Amigl%s;" % name)
    lines += ["    return NULL;", "}", ""]
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("%s: %d functions" % (out, len(funcs)))


if __name__ == "__main__":
    main()
