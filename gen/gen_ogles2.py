#!/usr/bin/env python3
"""Generate ogles2.library's dispatch table and everything that must agree
with it (plan section 6.6), from one source:

  khronos/gl.xml + api.txt   the GL entry points
  agl.txt                    the agl* entry points
  abi_order.txt              the table order: append-only, checked in

Usage:
  gen_ogles2.py --out DIR [--impl-dir ogles2] [--append]

--append adds API entries missing from abi_order.txt at its end; without it a
missing entry is an error. Entries are never reordered or removed: a line
"-name" retires an entry, which keeps its slot as a reserved NULL pointer.

Writes, under DIR:
  include/libraries/ogles2_dispatch.h  struct OGLES2Dispatch
  include/proto/ogles2.h               client wrappers (static inline + macro)
  ogles2/ogles2_api.h                  prototypes of the library's ogles2_* functions
  ogles2/dispatch_table.c              the table, with designated initialisers
  ogles2/stubs.c                       stubs for entries --impl-dir does not define
  client/agl_gen.c                     generated agl* import-library functions
  client/procaddr.c                    aglGetProcAddress: thunks + sorted name table
  tests/abi_layout.c                   compile-time check of every field's offset
"""
import argparse, os, re, sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = "/* GENERATED by gen/gen_ogles2.py - do not edit. */\n"
ABI_VERSION = 1


class Entry:
    def __init__(self, name, ret, params, kind, ctx="ctx", client="gen"):
        self.name = name          # glViewport, aglSwapBuffers
        self.ret = ret            # C return type
        self.params = params      # [(declaration, parameter name)] after the context
        self.kind = kind          # "gl" or "agl"
        self.ctx = ctx            # "ctx", "none" or "arg" (see agl.txt)
        self.client = client      # "gen" or "hand"

    @property
    def field(self):
        # GL fields are spelt "GLViewport": not "glViewport", which the client's
        # "#define glViewport OGLES2_glViewport" would rewrite, and not
        # "Viewport", which can be an AmigaOS macro (<proto/exec.h> defines
        # Enable() and Disable()). minigl's table uses the same spelling.
        return "GL" + self.name[2:] if self.kind == "gl" else self.name

    def lib_params(self):
        p = [d for d, _ in self.params]
        if self.ctx in ("ctx", "arg"):
            p = ["struct OGLES2Context *ctx"] + p
        return ", ".join(p) if p else "void"

    def call_args(self, ctx_expr):
        a = [n for _, n in self.params]
        if self.ctx == "ctx":
            a = [ctx_expr] + a
        return ", ".join(a)


def param_name(decl):
    m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", decl)
    return m.group(1)


def read_gl(xml_path, api_path):
    root = ET.parse(xml_path).getroot()
    commands = {}
    for c in root.find("commands").iter("command"):
        proto = c.find("proto")
        name = proto.find("name").text
        ret = "".join(proto.itertext())[: -len(name)].strip()
        params = []
        for p in c.findall("param"):
            decl = " ".join("".join(p.itertext()).split())
            params.append((decl, param_name(decl)))
        commands[name] = (ret, params)
    names = []
    for line in open(api_path):
        line = line.split("#", 1)[0].split()
        if not line:
            continue
        what, arg = line
        if what == "feature":
            feats = [f for f in root.iter("feature") if f.get("name") == arg]
            if not feats:
                sys.exit("api.txt: no feature %s in gl.xml" % arg)
            for req in feats[0].iter("require"):
                names += [c.get("name") for c in req.iter("command")]
        elif what == "command":
            names.append(arg)
        else:
            sys.exit("api.txt: unknown keyword %s" % what)
    out = []
    for n in names:
        if n not in commands:
            sys.exit("api.txt: %s is not a gl.xml command" % n)
        if n not in [e.name for e in out]:
            ret, params = commands[n]
            out.append(Entry(n, ret, params, "gl"))
    return out


def read_agl(path):
    out = []
    for line in open(path):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, ret, args, ctx, client = [x.strip() for x in line.split("|")]
        params = [(a.strip(), param_name(a)) for a in args.split(",") if a.strip()]
        if ctx not in ("ctx", "none", "arg") or client not in ("gen", "hand"):
            sys.exit("agl.txt: bad line for %s" % name)
        out.append(Entry(name, ret, params, "agl", ctx, client))
    return out


def read_order(path):
    order = []
    if os.path.exists(path):
        for line in open(path):
            line = line.split("#", 1)[0].strip()
            if line:
                order.append(line)
    return order


def resolve_order(entries, path, append):
    by = {e.name: e for e in entries}
    order = read_order(path)
    listed = {n.lstrip("-") for n in order}
    if len(listed) != len(order):
        sys.exit("abi_order.txt: an entry appears twice")
    for n in order:
        if not n.startswith("-") and n not in by:
            sys.exit("abi_order.txt: %s is in the table but no longer in the API; "
                     "retire it as -%s (never delete or reorder)" % (n, n))
    missing = [e.name for e in entries if e.name not in listed]
    if missing:
        if not append:
            sys.exit("abi_order.txt lacks %d entries (%s...); rerun with --append to add them "
                     "at the end" % (len(missing), ", ".join(missing[:4])))
        with open(path, "a", newline="\n") as f:
            if not order:
                f.write("# ogles2.library dispatch table order, after the 16-byte header.\n"
                        "# APPEND-ONLY: never reorder or delete; retire an entry as -name.\n")
            for n in missing:
                f.write(n + "\n")
        order += missing
        print("abi_order.txt: appended %d entries" % len(missing))
    return [by.get(n) if not n.startswith("-") else n for n in order]


def implemented(impl_dir):
    names = set()
    if not impl_dir or not os.path.isdir(impl_dir):
        return names
    rx = re.compile(r"^[A-Za-z_][\w \t\*]*?\bogles2_((?:gl|agl)\w+)\s*\(", re.M)
    for f in sorted(os.listdir(impl_dir)):
        if f.endswith(".c"):
            names |= set(rx.findall(open(os.path.join(impl_dir, f)).read()))
    return names


def write(out, rel, text):
    p = os.path.join(out, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", newline="\n") as f:
        f.write(text)


def default_return(ret):
    if ret == "void":
        return ""
    return "    return 0;\n"


def gen_dispatch_h(table):
    lines = [HEADER, "#ifndef LIBRARIES_OGLES2_DISPATCH_H\n#define LIBRARIES_OGLES2_DISPATCH_H\n\n",
             "#include <exec/types.h>\n#include <utility/tagitem.h>\n",
             "#ifndef GL_GLES_PROTOTYPES\n#define GL_GLES_PROTOTYPES 0\n#endif\n",
             "#include <GLES2/gl2.h>\n\n",
             "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n",
             "struct OGLES2Context; /* opaque */\nstruct BitMap;\n\n",
             "#define OGLES2_DISPATCH_ABI_VERSION %d\n" % ABI_VERSION,
             "#define OGLES2_DISPATCH_ENTRIES %d\n" % len(table),
             "#define OGLES2_BACKEND_PISTORM_V3D42 1\n\n",
             "struct OGLES2Dispatch\n{\n",
             "    ULONG abiVersion;   /* equal to OGLES2_DISPATCH_ABI_VERSION */\n",
             "    ULONG structSize;   /* at least sizeof(struct OGLES2Dispatch) */\n",
             "    ULONG backendFlags;\n    ULONG reserved;\n"]
    for i, e in enumerate(table):
        if isinstance(e, str):
            lines.append("    void *retired_%d; /* %s */\n" % (i, e[1:]))
        else:
            lines.append("    %s (*%s)(%s);\n" % (e.ret, e.field, e.lib_params()))
    lines.append("};\n\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n")
    return "".join(lines)


def gen_proto_h(table):
    gl = [e for e in table if not isinstance(e, str) and e.kind == "gl"]
    agl = [e for e in table if not isinstance(e, str) and e.kind == "agl"]
    L = [HEADER, "#ifndef PROTO_OGLES2_H\n#define PROTO_OGLES2_H\n\n",
         "#include <exec/types.h>\n#include <libraries/ogles2.h>\n",
         "#include <libraries/ogles2_dispatch.h>\n#include <clib/ogles2_protos.h>\n\n",
         "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n",
         "/* GCC, vbcc in C99 mode, C++: inline wrappers; other compilers: static. */\n",
         "#if defined(__GNUC__)\n#define OGLES2_INLINE static __inline__\n",
         "#elif defined(__cplusplus) || (defined(__STDC_VERSION__) && __STDC_VERSION__ >= 199901L)\n",
         "#define OGLES2_INLINE static inline\n#else\n#define OGLES2_INLINE static\n#endif\n\n",
         "/* In libogles2.a: one copy per program image (plan section 6.2). */\n",
         "extern const struct OGLES2Dispatch *OGLES2Dispatch;\n",
         "extern struct OGLES2Context *OGLES2CurrentContext;\n\n"]
    for e in agl:
        ret = "void *" if e.ret.startswith("struct OGLES2Context") else e.ret + " "
        args = [d for d, _ in e.params]
        if e.ctx == "arg":
            args = ["void *context"] + args
        L.append("%s%s(%s);\n" % (ret, e.name, ", ".join(args) if args else "void"))
    L.append("\n")
    for e in gl:
        # Parameter names get a trailing "_", so an application macro named
        # like a gl.xml parameter (x, count, index...) cannot break the header.
        decls = [re.sub(r"(\w+)(\s*(?:\[[^\]]*\])?)$", r"\1_\2", d) for d, _ in e.params]
        args = ", ".join(n + "_" for _, n in e.params)
        call = "OGLES2Dispatch->%s(OGLES2CurrentContext%s)" % (e.field, ", " + args if args else "")
        L.append("OGLES2_INLINE %s OGLES2_%s(%s)\n{ %s%s; }\n#define %s OGLES2_%s\n"
                 % (e.ret, e.name, ", ".join(decls) if decls else "void",
                    "" if e.ret == "void" else "return ", call, e.name, e.name))
    L.append("\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n")
    return "".join(L)


def gen_api_h(table):
    L = [HEADER, "#ifndef OGLES2_API_H\n#define OGLES2_API_H\n\n",
         "#include <libraries/ogles2_dispatch.h>\n\n",
         "/* Every table entry, as the library defines it. */\n"]
    for e in table:
        if not isinstance(e, str):
            L.append("%s ogles2_%s(%s);\n" % (e.ret, e.name, e.lib_params()))
    L.append("\n/* stubs.c: records GL_INVALID_OPERATION on ctx and logs the name once. */\n"
             "void ogles2_unimplemented(struct OGLES2Context *ctx, const char *name);\n\n#endif\n")
    return "".join(L)


# Entries that only read or write the calling context's own state fields
# (ctx->state, the viewport and scissor, the pixel store, the active texture
# unit, the error): nothing another member of a share group touches (a
# member's call changes other members' bindings, objects and jobs, never
# these), so they need no group semaphore and skip the wrapper (Quake III
# makes about 450 of them a frame: glDisable alone 310).
NO_GROUP_LOCK = {
    "glEnable", "glDisable", "glIsEnabled", "glBlendFunc", "glBlendFuncSeparate", "glBlendEquation",
    "glBlendEquationSeparate", "glBlendColor", "glDepthFunc", "glDepthMask", "glDepthRangef",
    "glCullFace", "glFrontFace", "glColorMask", "glClearColor", "glClearDepthf", "glClearStencil",
    "glStencilFunc", "glStencilFuncSeparate", "glStencilMask", "glStencilMaskSeparate", "glStencilOp",
    "glStencilOpSeparate", "glLineWidth", "glPolygonOffset", "glSampleCoverage", "glHint", "glScissor",
    "glViewport", "glPixelStorei", "glGetError", "glActiveTexture",
}


def wrapped(e):
    return e.ctx == "ctx" and e.name not in NO_GROUP_LOCK


def gen_table_c(table):
    L = [HEADER, '#include <proto/exec.h>\n#include "ogles2_internal.h"\n\n',
         "_Static_assert(sizeof(struct OGLES2Dispatch) == 16 + 4 * %d, \"table size\");\n\n"
         % len(table),
         "/* Every entry that takes the context runs under its share group's\n"
         " * semaphore while the group has two members or more (ogles2/share.c).\n"
         " * Both calls are tail calls: alone, the wrapper tests and jumps. */\n"]
    L.append("_Static_assert(__builtin_offsetof(struct OGLES2Context, share_lock) == 4, \"share_lock at 4\");\n"
             "_Static_assert(OGLES2_CONTEXT_MAGIC == 0x474c4532UL, \"the wrappers' magic\");\n\n")
    for e in table:
        if isinstance(e, str) or not wrapped(e):
            continue
        void = e.ret.strip() == "void"
        args = e.call_args("ctx")
        # the locked call, out of line
        L.append("%s ogles2_sl_%s(%s);\n" % (e.ret, e.name, e.lib_params()))
        L.append("__attribute__((noinline)) %s ogles2_sl_%s(%s)\n{\n" % (e.ret, e.name, e.lib_params()))
        L.append("    struct SignalSemaphore *l = ctx->share_lock;\n")
        if not void:
            L.append("    %s r;\n" % e.ret)
        L.append("    ObtainSemaphore(l);\n    %sogles2_%s(%s);\n    ReleaseSemaphore(l);\n%s}\n\n"
                 % ("" if void else "r = ", e.name, args, "" if void else "    return r;\n"))
        # the wrapper: the context (the first argument, above the return
        # address), its magic and share_lock tested, then a jump either way
        # with the arguments as they are on the stack
        L.append("%s ogles2_lk_%s(%s);\n" % (e.ret, e.name, e.lib_params()))
        L.append('__asm__("\\t.text\\n\\t.even\\n\\t.globl _ogles2_lk_%s\\n_ogles2_lk_%s:\\n"\n'
                 '        "\\tmove.l 4(%%sp),%%d0\\n\\tjeq 1f\\n\\tmove.l %%d0,%%a0\\n"\n'
                 '        "\\tcmp.l #0x474c4532,(%%a0)\\n\\tjne 1f\\n\\ttst.l 4(%%a0)\\n\\tjne 2f\\n"\n'
                 '        "1:\\tjmp _ogles2_%s\\n2:\\tjmp _ogles2_sl_%s\\n");\n\n'
                 % (e.name, e.name, e.name, e.name))
    L += ["const struct OGLES2Dispatch ogles2_dispatch_table = {\n",
          "    .abiVersion = OGLES2_DISPATCH_ABI_VERSION,\n",
          "    .structSize = sizeof(struct OGLES2Dispatch),\n",
          "    .backendFlags = OGLES2_BACKEND_PISTORM_V3D42,\n",
          "    .reserved = 0,\n"]
    for e in table:
        if not isinstance(e, str):
            L.append("    .%s = %s_%s,\n" % (e.field, "ogles2_lk" if wrapped(e) else "ogles2", e.name))
    L.append("};\n")
    return "".join(L)


def gen_stubs_c(table, done):
    L = [HEADER, '#include "ogles2_api.h"\n\n']
    n = 0
    for e in table:
        if isinstance(e, str) or e.name in done:
            continue
        n += 1
        unused = "".join("    (void)%s;\n" % p for _, p in e.params)
        ctx = "ctx" if e.ctx in ("ctx", "arg") else "0"
        L.append("%s ogles2_%s(%s)\n{\n%s    ogles2_unimplemented(%s, \"%s\");\n%s}\n\n"
                 % (e.ret, e.name, e.lib_params(), unused, ctx, e.name, default_return(e.ret)))
    return "".join(L), n


def gen_agl_c(table):
    L = [HEADER, "#include <proto/ogles2.h>\n\n"]
    for e in table:
        if isinstance(e, str) or e.kind != "agl" or e.client != "gen":
            continue
        if e.ctx == "arg":
            sys.exit("agl.txt: %s takes the context as argument; its client wrapper must be hand"
                     % e.name)
        ret = "void *" if e.ret.startswith("struct OGLES2Context") else e.ret + " "
        args = ", ".join(d for d, _ in e.params) or "void"
        body = "OGLES2Dispatch->%s(%s)" % (e.field, e.call_args("OGLES2CurrentContext"))
        guard = "    if (!OGLES2Dispatch)\n        return%s;\n" % ("" if e.ret == "void" else " 0")
        L.append("%s%s(%s)\n{\n%s    %s%s;\n}\n\n" % (ret, e.name, args, guard,
                                                    "" if e.ret == "void" else "return ", body))
    return "".join(L)


def gen_procaddr_c(table):
    gl = sorted((e for e in table if not isinstance(e, str) and e.kind == "gl"),
                key=lambda e: e.name.encode())
    L = [HEADER, "#include <string.h>\n#include <proto/ogles2.h>\n\n",
         "/* Context-free thunks for callers that look GL functions up by name\n"
         " * (SDL, gl4es): plan section 6.5. */\n"]
    for e in gl:
        args = ", ".join(n for _, n in e.params)
        call = "OGLES2Dispatch->%s(OGLES2CurrentContext%s)" % (e.field, ", " + args if args else "")
        L.append("static %s thunk_%s(%s)\n{ %s%s; }\n" % (
            e.ret, e.name, ", ".join(d for d, _ in e.params) or "void",
            "" if e.ret == "void" else "return ", call))
    L.append("\nstatic const struct { const char *name; void *fn; } names[%d] = {\n" % len(gl))
    for e in gl:
        L.append('    { "%s", (void *)thunk_%s },\n' % (e.name, e.name))
    L.append("};\n\nvoid *aglGetProcAddress(const char *name)\n{\n"
             "    int lo = 0, hi = %d - 1;\n" % len(gl) +
             "    if (!name)\n        return 0;\n"
             "    while (lo <= hi) {\n        int mid = (lo + hi) / 2;\n"
             "        int c = strcmp(name, names[mid].name);\n"
             "        if (c == 0)\n            return names[mid].fn;\n"
             "        if (c < 0)\n            hi = mid - 1;\n        else\n            lo = mid + 1;\n"
             "    }\n    return 0;\n}\n")
    return "".join(L)


def gen_abi_layout_c(table):
    # __builtin_offsetof, not offsetof: clib2's offsetof is the pointer-cast
    # macro, which GCC does not accept as a constant, so a typedef-array check
    # built on it silently became a run-time array and could never fail.
    L = [HEADER, "#include <stdio.h>\n#include <libraries/ogles2_dispatch.h>\n\n",
         "#define CHECK(name, expr) _Static_assert(expr, #name)\n",
         "#define OFS(field) __builtin_offsetof(struct OGLES2Dispatch, field)\n",
         "CHECK(abi_version, OGLES2_DISPATCH_ABI_VERSION == %d);\n" % ABI_VERSION,
         "CHECK(header, OFS(reserved) == 12);\n"]
    for i, e in enumerate(table):
        f = ("retired_%d" % i) if isinstance(e, str) else e.field
        L.append("CHECK(slot_%d_%s, OFS(%s) == %d);\n" % (i, f, f, 16 + 4 * i))
    L.append("CHECK(size, sizeof(struct OGLES2Dispatch) == %d);\n\n" % (16 + 4 * len(table)))
    L.append("int main(void)\n{\n    printf(\"PASS: ABI %d, %d entries, %d bytes\\n\");\n"
             "    return 0;\n}\n" % (ABI_VERSION, len(table), 16 + 4 * len(table)))
    return "".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--impl-dir", default=os.path.join(os.path.dirname(HERE), "ogles2"))
    ap.add_argument("--append", action="store_true")
    a = ap.parse_args()

    entries = read_agl(os.path.join(HERE, "agl.txt")) + \
        read_gl(os.path.join(HERE, "khronos", "gl.xml"), os.path.join(HERE, "api.txt"))
    table = resolve_order(entries, os.path.join(HERE, "abi_order.txt"), a.append)
    done = implemented(a.impl_dir)
    unknown = done - {e.name for e in table if not isinstance(e, str)}
    if unknown:
        sys.exit("%s defines ogles2_ functions that are not table entries: %s"
                 % (a.impl_dir, ", ".join(sorted(unknown))))

    write(a.out, "include/libraries/ogles2_dispatch.h", gen_dispatch_h(table))
    write(a.out, "include/proto/ogles2.h", gen_proto_h(table))
    write(a.out, "ogles2/ogles2_api.h", gen_api_h(table))
    write(a.out, "ogles2/dispatch_table.c", gen_table_c(table))
    stubs, nstubs = gen_stubs_c(table, done)
    write(a.out, "ogles2/stubs.c", stubs)
    write(a.out, "client/agl_gen.c", gen_agl_c(table))
    write(a.out, "client/procaddr.c", gen_procaddr_c(table))
    write(a.out, "tests/abi_layout.c", gen_abi_layout_c(table))
    live = sum(1 for e in table if not isinstance(e, str))
    print("gen_ogles2: %d entries (%d gl, %d agl), %d implemented, %d stubbed -> %s"
          % (len(table), sum(1 for e in table if not isinstance(e, str) and e.kind == "gl"),
             sum(1 for e in table if not isinstance(e, str) and e.kind == "agl"),
             live - nstubs, nstubs, a.out))


if __name__ == "__main__":
    main()
